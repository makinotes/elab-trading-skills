def audit(args: argparse.Namespace) -> Dict[str, Any]:
    output = Path(args.output).expanduser().resolve()
    crawl_audit_path = output / "qa" / "crawl_audit.json"
    if not crawl_audit_path.exists():
        raise ResearchError(
            f"No crawl audit found at {crawl_audit_path}. Run archive first."
        )
    crawl = read_json(crawl_audit_path, {})
    posts = read_jsonl(output / "archive" / "posts.jsonl")
    candidates = read_jsonl(output / "analysis" / "candidates.jsonl")
    reviewed = read_jsonl(output / "analysis" / "claims.reviewed.jsonl")
    candidates = resolve_claim_platforms(candidates, posts)
    reviewed = resolve_claim_platforms(reviewed, posts)
    market_rows = read_jsonl(output / "analysis" / "market" / "claims_market.jsonl")
    checks = []

    def add(name: str, passed: bool, severity: str, detail: Any) -> None:
        checks.append(
            {"name": name, "passed": bool(passed), "severity": severity, "detail": detail}
        )

    add(
        "crawl_audit_present",
        bool(crawl),
        "error",
        crawl.get("status") if isinstance(crawl, dict) else "missing",
    )
    add(
        "crawl_status_not_fail",
        bool(crawl) and crawl.get("status") != "FAIL",
        "error",
        crawl.get("status") if isinstance(crawl, dict) else "missing",
    )
    streams = crawl.get("streams") or [] if isinstance(crawl, dict) else []
    platform_by_uid: Dict[str, set] = defaultdict(set)
    for profile in crawl.get("profiles") or []:
        platform_by_uid[str(profile.get("uid") or "")].add(record_platform(profile))
    for row in list(posts) + list(streams):
        uid = str(row.get("profile_uid") or "")
        source = row.get("source") if isinstance(row.get("source"), dict) else {}
        if not row.get("platform") and not source.get("profile_url") and len(platform_by_uid[uid]) == 1:
            row["platform"] = next(iter(platform_by_uid[uid]))
    stream_pairs = {(profile_key(row), row.get("stream")) for row in streams}
    uids = {profile_key(row) for row in posts if row.get("profile_uid")}
    # Build per-uid expected stream list from crawl_audit profiles (set by each adapter).
    # Fall back to ["all", "columns"] (Futu default) for older archives lacking the field.
    uid_expected: Dict[str, List[str]] = {}
    for _p in (crawl.get("profiles") or [] if isinstance(crawl, dict) else []):
        if isinstance(_p, dict) and _p.get("uid"):
            uid_expected[profile_key(_p)] = list(_p.get("expected_streams") or ["all", "columns"])
    missing_streams = [
        f"{uid}:{label}"
        for uid in sorted(uids)
        for label in uid_expected.get(uid, ["all", "columns"])
        if (uid, label) not in stream_pairs
    ]
    add("expected_streams_present", not missing_streams, "error", missing_streams)
    incomplete_streams = [
        f"{row.get('profile_uid')}:{row.get('stream')}:{row.get('terminal_reason')}"
        for row in streams
        if not row.get("complete_for_request")
    ]
    add("streams_complete_for_request", not incomplete_streams, "error", incomplete_streams)
    # F2: uniqueness is now (profile_uid, feed_id).
    # Same feed_id across different profile_uids (cross-blogger repost of same post) is NOT a dup.
    # Self-reposts are merged at archive time so posts.jsonl should already be clean.
    feed_ids = [str(row.get("feed_id")) for row in posts]
    post_pairs = [
        (profile_key(row), str(row.get("feed_id") or ""))
        for row in posts
    ]
    duplicate_pairs = [
        f"{uid}:{fid}"
        for (uid, fid), count in Counter(post_pairs).items()
        if count > 1
    ]
    add("normalized_feed_ids_unique", not duplicate_pairs, "error", duplicate_pairs)
    missing_sources = []
    for row in posts:
        detail_path = str((row.get("source") or {}).get("detail_path") or "")
        if not detail_path or not Path(detail_path).exists():
            missing_sources.append(row.get("feed_id"))
    add("normalized_posts_trace_to_detail", not missing_sources, "error", missing_sources[:50])
    candidate_feeds = {(author_key(row), str(row.get("feed_id"))) for row in candidates}
    unknown_candidate_feeds = sorted(candidate_feeds - set(post_pairs))
    add("candidates_trace_to_posts", not unknown_candidate_feeds, "error", unknown_candidate_feeds[:50])
    post_by_feed = {(profile_key(row), str(row.get("feed_id"))): row for row in posts}
    unknown_reviewed_feeds = sorted(
        {
            f"{author_key(row)}:{row.get('feed_id')}"
            for row in reviewed
            if (author_key(row), str(row.get("feed_id"))) not in post_by_feed
        }
    )
    add(
        "reviewed_claims_trace_to_posts",
        not unknown_reviewed_feeds,
        "error",
        unknown_reviewed_feeds[:50],
    )
    invalid_reviewed = []
    allowed_evidence = {"A", "B", "C", "D"}
    allowed_directions = {"bullish", "bearish", "mixed", "neutral"}
    for row in reviewed:
        claim_id = row.get("claim_id") or row.get("candidate_id") or "unknown"
        required = ("feed_id", "author_uid", "published_at", "evidence_span")
        missing = [key for key in required if not row.get(key)]
        if missing:
            invalid_reviewed.append(f"{claim_id}:missing={','.join(missing)}")
        if row.get("evidence_level") not in allowed_evidence:
            invalid_reviewed.append(f"{claim_id}:invalid_evidence")
        if row.get("direction") not in allowed_directions:
            invalid_reviewed.append(f"{claim_id}:invalid_direction")
    add(
        "reviewed_claim_schema_minimum",
        not invalid_reviewed,
        "error",
        invalid_reviewed[:50],
    )
    untraceable_spans = []
    for row in reviewed:
        post = post_by_feed.get((author_key(row), str(row.get("feed_id"))))
        span = re.sub(r"\s+", " ", str(row.get("evidence_span") or "")).strip()
        source_text = re.sub(
            r"\s+",
            " ",
            f"{(post or {}).get('title') or ''} {(post or {}).get('text') or ''}",
        ).strip()
        if post and span and span not in source_text:
            untraceable_spans.append(row.get("claim_id") or row.get("candidate_id"))
    add(
        "reviewed_evidence_spans_trace_to_text",
        not untraceable_spans,
        "error",
        untraceable_spans[:50],
    )
    invalid_a = [
        row.get("claim_id")
        for row in reviewed
        if row.get("evidence_level") == "A"
        and (
            not row.get("image_evidence_verified")
            or not row.get("image_evidence_paths")
        )
    ]
    add("evidence_A_has_verified_source", not invalid_a, "error", invalid_a)
    missing_a_paths = []
    for row in reviewed:
        if row.get("evidence_level") != "A":
            continue
        for value in row.get("image_evidence_paths") or []:
            path = Path(str(value))
            if not path.is_absolute():
                path = output / path
            if not path.exists():
                missing_a_paths.append(f"{row.get('claim_id')}:{value}")
    add("evidence_A_paths_exist", not missing_a_paths, "error", missing_a_paths[:50])
    valid_claim_ids = {
        str(row.get("claim_id") or row.get("candidate_id") or "")
        for row in (reviewed or candidates)
    }
    unknown_market_claims = sorted(
        {
            str(row.get("claim_id"))
            for row in market_rows
            if str(row.get("claim_id")) not in valid_claim_ids
        }
    )
    add(
        "market_rows_trace_to_frozen_claims",
        not unknown_market_claims,
        "error",
        unknown_market_claims[:50],
    )
    binding_errors = market_binding_errors(reviewed or candidates, market_rows)
    add("market_rows_match_frozen_claims", not binding_errors, "error", binding_errors[:50])
    time_violations = []
    for row in market_rows:
        published = parse_claim_time(row.get("published_at"))
        cutoff = row.get("context_cutoff")
        evaluation = row.get("evaluation_open_date")
        if published and cutoff and str(cutoff) >= published.astimezone(CN_TZ).date().isoformat():
            time_violations.append(f"{row.get('claim_id')}:context")
        if published and evaluation and str(evaluation) <= published.astimezone(CN_TZ).date().isoformat():
            time_violations.append(f"{row.get('claim_id')}:evaluation")
    add("market_no_time_travel", not time_violations, "error", time_violations[:50])
    directional_reviewed_ids = {
        str(row.get("claim_id") or row.get("candidate_id") or "")
        for row in reviewed
        if row.get("symbol_raw") and row.get("direction") in {"bullish", "bearish"}
    }
    market_claim_ids = {
        str(row.get("claim_id") or "") for row in market_rows if row.get("claim_id")
    }
    missing_market_claims = sorted(directional_reviewed_ids - market_claim_ids)
    if directional_reviewed_ids:
        add(
            "reviewed_directional_claims_have_market_rows",
            bool(market_rows),
            "error",
            {
                "directional_reviewed": len(directional_reviewed_ids),
                "market_rows": len(market_rows),
            },
        )
        add(
            "reviewed_market_row_coverage",
            not missing_market_claims,
            "warning",
            missing_market_claims[:50],
        )
    provider_missing = [
        str(row.get("claim_id"))
        for row in market_rows
        if row.get("missing_reason")
    ]
    add(
        "market_provider_and_forward_data_coverage",
        not provider_missing,
        "warning",
        provider_missing[:50],
    )
    media_failures = crawl.get("media_failures") or [] if isinstance(crawl, dict) else []
    add(
        "media_failures_disclosed",
        not media_failures,
        "warning",
        len(media_failures),
    )
    # F3: Tripwire for silent media-extraction regressions (e.g. dict-valued
    # orgPic/bigPic not handled).  Denominator changes to posts_with_image_content
    # (posts that actually have image URLs in source) rather than total post count,
    # preventing false alarms on pure-text blogger archives.
    _media_mode = (
        str(crawl.get("media_mode") or ("none" if crawl.get("skip_media") else "all"))
        if isinstance(crawl, dict) else "all"
    )
    _media_objects = int(crawl.get("media_objects") or 0) if isinstance(crawl, dict) else 0
    _posts_with_images = int(crawl.get("posts_with_image_content") or 0) if isinstance(crawl, dict) else 0
    if _media_mode == "none":
        add(
            "media_extraction_not_zero_jobs",
            True,
            "info",
            "skipped_by_mode=none",
        )
    elif _posts_with_images == 0:
        add(
            "media_extraction_not_zero_jobs",
            True,
            "info",
            f"N/A (posts_with_image_content=0; text-only archive or no qualifying posts)",
        )
    elif _media_objects == 0:
        add(
            "media_extraction_not_zero_jobs",
            False,
            "warning",
            (
                f"mode={_media_mode}, posts_with_image_content={_posts_with_images}, "
                "media_objects=0 — extraction produced zero jobs while image posts exist; "
                "possible nested-structure extraction regression"
            ),
        )
    else:
        add(
            "media_extraction_not_zero_jobs",
            True,
            "info",
            f"media_objects={_media_objects} mode={_media_mode} posts_with_image_content={_posts_with_images}",
        )
    add(
        "reviewed_claims_available",
        bool(reviewed),
        "warning",
        f"{len(reviewed)} reviewed; {len(candidates)} machine candidates",
    )
    add(
        "sample_size_boundary",
        True,
        "info",
        "Per-author/window N<20 must remain descriptive; larger samples still require uncertainty and FDR checks.",
    )
    add(
        "structural_missingness_disclosed",
        True,
        "info",
        "Deleted/private/restricted posts, survivor bias, OCR limits, and daily-data limits remain.",
    )

    failed_errors = [row for row in checks if not row["passed"] and row["severity"] == "error"]
    warnings = [row for row in checks if not row["passed"] and row["severity"] == "warning"]
    status = "FAIL" if failed_errors else "WARN" if warnings else "PASS"
    result = {
        "schema_version": SCHEMA_VERSION,
        "generated_at": now_iso(),
        "status": status,
        "checks": checks,
        "publication_gate": {
            "data_chain_passed": not failed_errors,
            "reviewed_claims_present": bool(reviewed),
            "public_comparative_conclusion_allowed": not failed_errors and bool(reviewed),
            "market_performance_conclusion_allowed": (
                not failed_errors
                and bool(reviewed)
                and bool(market_rows)
                and not provider_missing
            ),
            "note": "PASS validates traceability and chronology, not stable alpha.",
        },
    }
    atomic_write_json(confined_path(output, "qa", "adversarial_audit.json"), result)
    log(
        f"Adversarial audit {status}: errors={len(failed_errors)} warnings={len(warnings)}"
    )
    return result


def doctor(args: argparse.Namespace) -> Dict[str, Any]:
    result: Dict[str, Any] = {
        "tool": "elab-futu-research",
        "tool_version": VERSION,
        "checked_at": now_iso(),
        "python": {
            "version": ".".join(str(item) for item in sys.version_info[:3]),
            "supported": sys.version_info >= (3, 9),
        },
        "output_writable": None,
        "profile_uid": None,
        "futu_list_endpoints": {
            label: {"checked": False, "ok": None, "error": None}
            for label in STREAMS.values()
        },
        "tiger_personal_endpoint": None,
        "notes": [
            "Core workflow has no third-party Python dependency.",
            "No browser cookie, token, or API key is read.",
        ],
    }
    if getattr(args, "output", None):
        output = Path(args.output).expanduser().resolve()
        try:
            output.mkdir(parents=True, exist_ok=True)
            probe = output / ".elab-futu-write-probe"
            atomic_write_text(probe, "ok")
            probe.unlink()
            result["output_writable"] = True
        except OSError as error:
            result["output_writable"] = False
            result["output_error"] = str(error)
    profiles = getattr(args, "profile", None) or []
    if profiles:
        profile_input = profiles[0]
        try:
            adp = select_adapter(profile_input)
        except ResearchError:
            adp = _FUTU_ADAPTER  # fallback; error surfaced below
        if adp.name == "tiger":
            # Tiger branch: probe the personal page endpoint.
            try:
                uid = adp.resolve_uid(profile_input)
            except ResearchError as error:
                uid = ""
                result["tiger_personal_endpoint"] = {
                    "checked": True,
                    "ok": False,
                    "error": str(error),
                }
            result["profile_uid"] = uid
            if uid and result.get("tiger_personal_endpoint") is None:
                personal_url = adp.profile_url(uid)
                tiger_probe: Dict[str, Any] = {
                    "checked": True,
                    "url": personal_url,
                    "ok": None,
                    "error": None,
                    "http_status": None,
                    "content_bytes": None,
                }
                try:
                    html_text = _tiger_fetch_html(personal_url, attempts=2, timeout=20)
                    tiger_probe["ok"] = True
                    tiger_probe["content_bytes"] = len(html_text.encode("utf-8"))
                    post_ids, _, _ = TigerAdapter()._parse_list_page(
                        html_text, datetime.now(CN_TZ).date()
                    )
                    tiger_probe["sample_post_count"] = len(post_ids)
                except ResearchError as error:
                    tiger_probe["ok"] = False
                    tiger_probe["error"] = str(error)
                result["tiger_personal_endpoint"] = tiger_probe
        else:
            # Futu branch: parse numeric UID and probe list endpoints.
            try:
                uid = parse_uid(profile_input)
            except ResearchError as error:
                uid = ""
                result["notes"].append(f"UID parse error: {error}")
            result["profile_uid"] = uid
            if uid:
                for feed_type, label in STREAMS.items():
                    probe = result["futu_list_endpoints"][label]
                    probe["checked"] = True
                    try:
                        payload = request_json(
                            LIST_URL,
                            {
                                "type": feed_type,
                                "num": 1,
                                "load_list_type": 2,
                                "target_uid": uid,
                            },
                        )
                        validate_list_payload(payload)
                        probe["ok"] = True
                        probe["sample_rows"] = len(payload.get("feed") or [])
                        probe["has_more_present"] = "has_more" in payload
                    except Exception as error:
                        probe["ok"] = False
                        probe["error"] = str(error)
    endpoint_failed = any(
        item["ok"] is False for item in result["futu_list_endpoints"].values()
    )
    tiger_failed = (
        isinstance(result.get("tiger_personal_endpoint"), dict)
        and result["tiger_personal_endpoint"].get("ok") is False
    )
    if not profiles:
        # No profile supplied: endpoint connectivity was never tested.
        result["status"] = "PARTIAL"
        result["note"] = "no profile supplied; endpoint checks skipped"
    elif (
        result["python"]["supported"]
        and result["output_writable"] is not False
        and not endpoint_failed
        and not tiger_failed
    ):
        result["status"] = "PASS"
    else:
        result["status"] = "FAIL"
    print(json.dumps(result, ensure_ascii=False, indent=2))
    return result


