def _resolve_cn_tz() -> Any:
    """Resolve China Standard Time (UTC+8).

    Prefers ZoneInfo("Asia/Shanghai") when the timezone database is available.
    Falls back to a fixed UTC+8 offset when ZoneInfo or its data is missing
    (e.g. Windows without the tzdata package).

    Asia/Shanghai has had no Daylight Saving Time since 1991-09-15, so the
    fixed +8 offset is semantically equivalent to the IANA zone for any
    timestamp in the modern era. No date-bucketing skew occurs.
    """
    try:
        from zoneinfo import ZoneInfo
        return ZoneInfo("Asia/Shanghai")
    except Exception:
        return timezone(timedelta(hours=8))


