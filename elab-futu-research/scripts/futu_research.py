def extract_media_urls(detail: Dict[str, Any]) -> List[Dict[str, str]]:
    found: Dict[str, Dict[str, str]] = {}

    def collect_url(url: Any, source_field: str) -> bool:
        """Add url to found when it is a real HTTP image URL. Returns True if collected."""
        if (
            isinstance(url, str)
            and url.startswith(("https://", "http://"))
            and "spacer.gif" not in url
        ):
            found[url] = {"url": url, "source_field": source_field}
            return True
        return False

    def visit_picture_item(item: Dict[str, Any]) -> None:
        """Handle a pictureItem dict (orgPic/bigPic/thumbPic siblings) with priority.

        Priority: orgPic (evidence-grade original) > bigPic (fallback).
        thumbPic is intentionally excluded to avoid triple-downloading the same image.
        """
        for key in ("orgPic", "bigPic"):
            child = item.get(key)
            if isinstance(child, dict):
                if collect_url(child.get("url"), key):
                    return  # collected highest available; stop
            elif isinstance(child, str):
                if collect_url(child, key):
                    return

    def visit(value: Any, parent_key: str = "") -> None:
        if isinstance(value, list):
            for item in value:
                visit(item, parent_key)
        elif isinstance(value, dict):
            # Detect pictureItem containers (sibling orgPic/bigPic/thumbPic keys) and apply
            # priority logic instead of visiting each key independently.  This avoids
            # downloading the same photo at three quality levels.
            if any(k in value for k in ("orgPic", "bigPic", "thumbPic")):
                visit_picture_item(value)
                # Still recurse into non-picture-priority keys (e.g. stockIds, text).
                for key, child in value.items():
                    if key not in ("orgPic", "bigPic", "thumbPic"):
                        visit(child, key)
                return
            for key, child in value.items():
                normalized = key.lower().replace("-", "").replace(" ", "")
                if isinstance(child, str) and child.startswith(("https://", "http://")):
                    if normalized in URL_MEDIA_KEYS or (
                        parent_key.lower() in {"image", "images", "pic", "pics"}
                        and re.search(r"\.(?:jpe?g|png|webp|gif)(?:[?#]|$)", child, re.I)
                    ):
                        if "spacer.gif" not in child:
                            found[child] = {"url": child, "source_field": key}
                elif normalized in URL_MEDIA_KEYS and isinstance(child, dict):
                    # dict-valued media key (e.g. display, preview) — extract .url directly.
                    # The real Futu structure wraps URL strings in {url, width, height} dicts;
                    # the old isinstance(child, str) check silently missed these.
                    collect_url(child.get("url"), key)
                else:
                    visit(child, key)

    visit(detail.get("moduleData") or [])
    return list(found.values())


def extension_for(url: str, content_type: str) -> str:
    mapping = {
        "image/jpeg": ".jpg",
        "image/png": ".png",
        "image/webp": ".webp",
        "image/gif": ".gif",
    }
    mime = (content_type or "").split(";", 1)[0].strip().lower()
    if mime in mapping:
        return mapping[mime]
    suffix = Path(urllib.parse.urlparse(url).path).suffix.lower()
    return suffix if suffix in {".jpg", ".jpeg", ".png", ".webp", ".gif"} else ".bin"


def download_media(
    uid: str,
    detail_paths: Sequence[Path],
    output: Path,
    workers: int,
    media_mode: str = "all",
) -> List[Dict[str, Any]]:
    """Download media for the given detail files.

    media_mode controls which posts' media are downloaded:
      'all'      — download all (default, same as pre-v1.2.0 behaviour)
      'evidence' — only posts where is_repost=False and text matches
                   EVIDENCE_MEDIA_KEYWORDS; others get a skip record in manifest
      'none'     — caller should not reach here (archive() guards this)
    """
    uid = safe_component(uid, "UID")
    jobs: List[Tuple[str, int, Dict[str, str]]] = []
    skip_records: List[Dict[str, Any]] = []

    for path in detail_paths:
        envelope = read_json(path, {})
        detail = detail_data(envelope)
        feed_id = safe_component((detail.get("feedCommon") or {}).get("feedId") or path.stem, "feed ID")
        media_urls = extract_media_urls(detail)

        if media_mode == "evidence" and media_urls:
            qualifies, reason = _post_qualifies_for_evidence_media(envelope)
            if not qualifies:
                for index, item in enumerate(media_urls, start=1):
                    skip_records.append({
                        "uid": uid,
                        "feed_id": feed_id,
                        "index": index,
                        "status": "skipped",
                        "skip_reason": f"mode=evidence,matched=False,reason={reason}",
                        "url": item["url"],
                        "source_field": item["source_field"],
                    })
                continue

        for index, item in enumerate(media_urls, start=1):
            jobs.append((feed_id, index, item))

    def fetch_one(job: Tuple[str, int, Dict[str, str]]) -> Dict[str, Any]:
        feed_id, index, item = job
        base = confined_path(output, "media", uid, feed_id)
        existing = sorted(base.glob(f"{index:03d}.*")) if base.exists() else []
        for path in existing:
            confined_path(output, str(path.relative_to(output)))
            if path.suffix != ".part" and path.stat().st_size > 0:
                return {
                    "uid": uid,
                    "feed_id": feed_id,
                    "index": index,
                    "status": "ok",
                    "source": "cache",
                    "url": item["url"],
                    "source_field": item["source_field"],
                    "path": str(path.relative_to(output)),
                    "bytes": path.stat().st_size,
                    "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
                }
        try:
            body, metadata = request_bytes(item["url"], attempts=4)
            content_type = metadata.get("content_type", "")
            if not content_type.lower().startswith("image/"):
                raise ResearchError(f"non-image content type {content_type!r}")
            extension = extension_for(item["url"], content_type)
            path = base / f"{index:03d}{extension}"
            path.parent.mkdir(parents=True, exist_ok=True)
            with tempfile.NamedTemporaryFile(dir=path.parent, prefix=".elab-", suffix=".part", delete=False) as handle:
                temporary = Path(handle.name)
                try:
                    handle.write(body)
                    handle.close()
                    os.replace(temporary, path)
                finally:
                    if temporary.exists():
                        temporary.unlink()
            return {
                "uid": uid,
                "feed_id": feed_id,
                "index": index,
                "status": "ok",
                "source": "network",
                "url": item["url"],
                "source_field": item["source_field"],
                "path": str(path.relative_to(output)),
                "content_type": content_type,
                "bytes": len(body),
                "sha256": hashlib.sha256(body).hexdigest(),
            }
        except Exception as error:
            return {
                "uid": uid,
                "feed_id": feed_id,
                "index": index,
                "status": "failed",
                "url": item["url"],
                "source_field": item["source_field"],
                "error": str(error),
            }

    items: List[Dict[str, Any]] = []
    with concurrent.futures.ThreadPoolExecutor(max_workers=max(1, min(workers, 6))) as pool:
        for index, result in enumerate(pool.map(fetch_one, jobs), start=1):
            items.append(result)
            if index % 50 == 0 or index == len(jobs):
                failures = sum(item["status"] != "ok" for item in items)
                log(f"[{uid}/media] {index}/{len(jobs)} failed={failures}")
    # Append evidence-mode skip records (status='skipped') after download records.
    # The manifest merging loop in archive() treats any status != 'ok' as non-preferred,
    # so skip records are stored but never replace successful download entries.
    return items + skip_records


def normalize_detail(
    path: Path,
    uid: str,
    stream_membership: Sequence[str],
    media_by_feed: Dict[str, List[Dict[str, Any]]],
    profile_url: str,
) -> Dict[str, Any]:
    envelope = read_json(path)
    if not isinstance(envelope, dict):
        raise ResearchError(f"Cannot parse detail file {path}")
    validate_detail_payload(envelope)
    detail = detail_data(envelope)
    common = detail.get("feedCommon") or {}
    timestamp = safe_int(common.get("timestamp"), 0)
    published = (
        datetime.fromtimestamp(timestamp, CN_TZ).isoformat(timespec="seconds")
        if timestamp
        else None
    )
    author = detail.get("authorInfo") or {}
    author_uid = str(author.get("userId") or "")
    uid = safe_component(uid, "UID")
    feed_id = safe_component(common.get("feedId") or path.stem, "feed ID")
    title = clean_text(str(detail.get("feedTitle") or ""))
    modules = detail.get("moduleData") or []

    # Repost detection: the original author-UID comparison (author_uid == uid) is
    # insufficient because self-reposts share the same UID yet carry the original
    # post nested under feedModel.original / moduleData[i].data.origin.
    _orig_obj = _repost_original_obj(detail)
    _author_mismatch = bool(author_uid) and author_uid != uid
    _is_repost = bool(_orig_obj) or _author_mismatch

    if _is_repost:
        # Own comment = text from non-repost modules; repost content goes to original_text.
        text = module_text_own(modules)
        original_text: Optional[str] = _text_from_rich_items(_orig_obj) if _orig_obj else None
        _raw_orig_author = (
            (_orig_obj.get("authorName") or _orig_obj.get("nickName")) if _orig_obj else None
        )
        original_author: Optional[str] = str(_raw_orig_author) if _raw_orig_author else None
        # Title: prefer own comment; fall back to "转发：<original preview>" to avoid
        # the repost content being echoed verbatim as both text and title.
        if not title:
            if text:
                title = text[:80]
            elif original_text:
                title = f"转发：{original_text[:50]}"
    else:
        text = module_text(modules)
        original_text = None
        original_author = None

    tagged = recursively_collect_symbols(modules)
    tagged_values = {item["raw"] for item in tagged}
    inferred = [
        item for item in inferred_symbols(f"{title}\n{text}") if item["raw"] not in tagged_values
    ]
    counts = detail.get("count") or {}
    feed_type = safe_int(common.get("feedType"), 0)
    action = (common.get("dynamicDescription") or {})
    if isinstance(action, dict):
        profile_action = (
            action.get("stringSc")
            or action.get("stringTc")
            or action.get("stringEn")
            or ""
        )
    else:
        profile_action = str(action or "")
    media_items = sorted(
        media_by_feed.get(feed_id, []), key=lambda item: safe_int(item.get("index"), 0)
    )
    original = not _is_repost
    warnings = []
    if not timestamp:
        warnings.append("timestamp_parse_error")
    if not text and not title:
        warnings.append("empty_extractable_text")
    return {
        "schema_version": SCHEMA_VERSION,
        "platform": "futu",
        "feed_id": feed_id,
        "author_uid": author_uid or uid,
        "profile_uid": uid,
        "author_name": str(author.get("nickName") or "") or None,
        "published_at": published,
        "published_at_raw": common.get("timestamp"),
        "date": published[:10] if published else None,
        "month": published[:7] if published else "unknown",
        "stream_membership": sorted(set(stream_membership)),
        "is_column": "columns" in stream_membership or feed_type == 4,
        "is_repost": not original,
        "is_original_author": original,
        "feed_type": feed_type,
        "content_type": TYPE_LABELS.get(feed_type, "其他动态"),
        "profile_action": profile_action,
        "title": title,
        "text": text,
        "original_text": original_text,
        "original_author": original_author,
        "symbols": tagged,
        "inferred_symbols": inferred,
        "topics": topic_names(detail),
        "metrics": {
            "comments": safe_int(counts.get("comment"), 0),
            "likes": like_count(detail),
            "reposts": safe_int(counts.get("share"), 0),
            "views": safe_int(counts.get("browse"), 0),
        },
        "images": [
            {
                "url": item.get("url"),
                "source_field": item.get("source_field"),
                "local_path": item.get("path") if item.get("status") == "ok" else None,
                "status": item.get("status"),
            }
            for item in media_items
        ],
        "url": f"https://q.futunn.com/feed/{feed_id}?lang=zh-cn",
        "source": {
            "detail_path": str(path),
            "profile_url": profile_url,
        },
        "parse_warnings": warnings,
    }


def within_requested_range(
    timestamp: int,
    since_dt: Optional[datetime],
    until_dt: Optional[datetime],
) -> bool:
    if not timestamp:
        return True
    if since_dt and timestamp < int(since_dt.timestamp()):
        return False
    if until_dt and timestamp > int(until_dt.timestamp()):
        return False
    return True


def write_archive_files(output: Path, records: Sequence[Dict[str, Any]]) -> None:
    archive = confined_path(output, "archive")
    archive.mkdir(parents=True, exist_ok=True)
    ordered = sorted(
        records,
        key=lambda row: (row.get("published_at") or "", row.get("feed_id") or ""),
        reverse=True,
    )
    write_jsonl(archive / "posts.jsonl", ordered)
